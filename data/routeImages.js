function normalizeRouteKey(value) {
  return String(value ?? "")
    .trim()
    .replace(/\\/g, "/")
    .split("/")
    .pop()
    .replace(/\.(png|jpe?g|webp)$/i, "")
    .normalize("NFD")
    .replace(/[\u0300-\u036f]/g, "")
    .toLowerCase()
    .replace(/[^a-z0-9]/g, "");
}

const routeLookup = new Map();

Object.entries(ROUTE_IMAGES).forEach(([key, source]) => {
  routeLookup.set(normalizeRouteKey(key), source);

  (ALIASES[key] || []).forEach((alias) => {
    routeLookup.set(normalizeRouteKey(alias), source);
  });
});

// Accepts a journey object, a route key, or multiple candidates.
// Unknown journeys return null instead of unrelated artwork.
export function getRouteImage(...candidates) {
  for (const candidate of candidates) {
    if (candidate == null) continue;

    const values =
      typeof candidate === "object"
        ? [
            candidate.routeKey,
            candidate.journeyKey,
            candidate.journeyId,
            candidate.id,
            candidate.slug,
            candidate.title,
            candidate.name,
          ]
        : [candidate];

    for (const value of values) {
      if (typeof value !== "string") continue;

      const source = routeLookup.get(normalizeRouteKey(value));

      if (source != null) return source;
    }
  }

  return null;
}

