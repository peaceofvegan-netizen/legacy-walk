// ============================================================
// GET TRANSLATED JOURNEY
// ============================================================

export function getJourneyTranslation(
  journey,
  language = "en"
) {
  if (!journey) {
    return journey;
  }

  const translated =
    journeyTranslations?.[
      journey.id
    ]?.[
      language
    ];

  if (!translated) {
    return journey;
  }

  return {
    ...journey,

    title:
      translated.title ||
      journey.title,

    subtitle:
      translated.subtitle ||
      journey.subtitle,
  };
}

// ============================================================
// GET TRANSLATED JOURNEY ARRAY
// ============================================================

export function localizeJourneys(
  journeys = [],
  language = "en"
) {
  return journeys.map(
    journey =>
      getJourneyTranslation(
        journey,
        language
      )
  );
}

export default journeyTranslations;