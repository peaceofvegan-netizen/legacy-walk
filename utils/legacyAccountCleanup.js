export async function removeLegacyAccountData(userId) {
  const keys = (await DeviceStorage.getAllKeys()).filter(key =>
    LEGACY_KEYS.has(key) || LEGACY_PREFIXES.some(prefix => key.startsWith(prefix)) ||
    key === `LEGATHON_WCOIN_CACHE:${userId}`
  );
  if (keys.length) await DeviceStorage.multiRemove(keys);
}
